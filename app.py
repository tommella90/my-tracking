                dark = darker_color(base_color)
                ax_h.plot(ma.index, ma.to_numpy(), color=dark, linewidth=2.5, zorder=3)
                ma_handles.append(
                    plt.Line2D([0], [0], color=dark, linewidth=2.5, label=label)
                )

