corr_df = corr_df.apply(pd.to_numeric, errors='coerce')

# Keep only columns with at least 3 valid values in the selected range
corr_df = corr_df[[c for c in corr_df.columns if corr_df[c].count() >= 3]]

if len(corr_df.columns) >= 2:
    corr = corr_df.corr()

    fig4, ax4 = plt.subplots(figsize=(12, 10))
    im = ax4.imshow(corr.values, cmap='coolwarm', vmin=-1, vmax=1)

    n = len(corr.columns)
    ax4.set_xticks(range(n))
    ax4.set_yticks(range(n))
    ax4.set_xticklabels(corr.columns, rotation=45, ha='right', fontsize=9)
    ax4.set_yticklabels(corr.columns, fontsize=9)

    # Annotate each cell with the correlation value
    for i in range(n):
        for j in range(n):
            value = corr.values[i, j]
            ax4.text(j, i, f"{value:.2f}",
                     ha='center', va='center', fontsize=7,
                     color='white' if abs(value) > 0.6 else '#333333')

    for spine in ax4.spines.values():
        spine.set_visible(False)
    ax4.set_title("Pearson correlation (selected date range)", fontsize=14, fontweight='bold')

    fig4.tight_layout()
    st.pyplot(fig4)
    st.caption(
        "Correlations are computed on the days where both variables have a value, "
        "so pairs can differ in the number of days used."
    )

    # --- Bar chart: top 10 strongest variable pairs ---
    cols = corr.columns
    pair_rows = []
    for i in range(len(cols)):
        for j in range(i + 1, len(cols)):
            r = corr.iloc[i, j]
            if pd.notna(r):
                pair_rows.append((f"{cols[i]}  ↔  {cols[j]}", r))
    pair_rows.sort(key=lambda p: abs(p[1]), reverse=True)
    top_pairs = pair_rows[:10]

    if top_pairs:
        # reverse so the strongest pair is at the top of the chart
        pair_labels = [p[0] for p in top_pairs][::-1]
        pair_values = [p[1] for p in top_pairs][::-1]

        fig5, ax5 = plt.subplots(figsize=(12, max(4, 0.55 * len(top_pairs))))

        ax5.barh(pair_labels, pair_values,
                 color=[plt.cm.coolwarm((v + 1) / 2) for v in pair_values])

        # Zero reference line and value labels at the bar ends
        ax5.axvline(0, color=COLORS['spine'], linewidth=0.8)
        for y, v in enumerate(pair_values):
            ax5.text(v + (0.02 if v >= 0 else -0.02), y, f"{v:+.2f}",
                     va='center', ha='left' if v >= 0 else 'right',
                     fontsize=9, color=COLORS['spine'])

        ax5.set_xlim(-1.05, 1.05)
        ax5.set_title("Top 10 correlated variable pairs (by |r|)",
                      fontsize=14, fontweight='bold')

        for spine_name, spine in ax5.spines.items():
            spine.set_visible(spine_name == 'bottom')
            if spine_name == 'bottom':
                spine.set_linewidth(0.8)
                spine.set_color(COLORS['spine'])
        ax5.grid(axis='x', alpha=COLORS['grid_alpha'])
        ax5.grid(axis='y', visible=False)
        ax5.tick_params(axis='y', labelsize=9)

        fig5.tight_layout()
        st.pyplot(fig5)
else:
    st.info("Not enough data with values in the selected date range to compute correlations.")