def get_spread_colors(n):
    """Pick n colors from custom palette."""
    if n <= 0:
        return []
    # Use first n colors from the palette
    return VARIABLE_COLORS[:n]

# --- Data Loading ---
DAILY_CSV = 'data/unified/daily.csv'

@st.cache_data
def load_data():
    # Merged daily data (energy tracker + Polar device), generated by
    # scripts/unify_polar_data.py
    if os.path.exists(DAILY_CSV):
        df = pd.read_csv(DAILY_CSV, index_col=0, parse_dates=True)
        df.index.name = 'date'
        df = df.reset_index()
        df['asleep_hours'] = df.get('asleep_s') / 3600
        return df.sort_values('date').reset_index(drop=True)

    # Fallback: raw energy tracker only (no Polar columns)
    st.warning(
        f"{DAILY_CSV} not found. Run `python scripts/unify_polar_data.py` "
        "to generate it. Falling back to the raw energy tracker."
    )
    df = pd.read_excel('data/otherData/energy_tracker.ods', engine='odf', index_col=0)
    df.index.name = 'date'
    df = df.reset_index()
    df['total activity'] = df['total activity'].astype(str).str.replace('s', '', regex=False)
    df['total activity'] = pd.to_numeric(df['total activity'], errors='coerce')
    df['physical activity'] = df['physical activity'].fillna(0)
    df['physical activity'] = pd.to_numeric(df['physical activity'], errors='coerce')
    df['exertion'] = pd.to_numeric(df['exertion'], errors='coerce')
    df = df.dropna(subset=['date']).sort_values('date').reset_index(drop=True)
    return df

df = load_data()

# --- Continuous (sample-level) data sources ---
CONTINUOUS_DIR = 'data/unified/continuous'
# label -> (file, metric filter inside file, value column)
CONTINUOUS_SOURCES = {
    'Heart rate (bpm)': ('hr.csv', None, 'heart_rate'),
    'METs (30 s)': ('activity_samples.csv', 'mets', 'value'),
    'Steps (per min)': ('activity_samples.csv', 'steps', 'value'),
    'Skin temperature (°C)': ('skin_temperature.csv', None, 'temperature_celsius'),
}

@st.cache_data
def load_continuous_signal(filename, metric, value_col):
    """Load one sample-level signal from the continuous data folder."""
    path = os.path.join(CONTINUOUS_DIR, filename)
    if not os.path.exists(path):
        return None
    df = pd.read_csv(path)
    if metric is not None and 'metric' in df.columns:
        df = df[df['metric'] == metric]
    df['timestamp'] = pd.to_datetime(df['timestamp'])
    return df[['timestamp', value_col]].rename(columns={value_col: 'value'})

